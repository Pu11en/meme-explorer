#!/usr/bin/env python3
"""
Real-time dev-reputation ledger — find wallets that launch winners, fast.

Unlike the Dune watchlist (a 3-min batch SQL query regenerated by hand every
couple weeks), this accumulates from our OWN recordings, one batch at a time,
while the raw wallet data is still on disk. A dev who lands their 2nd organic
migration surfaces in the ranked list within ~1 hour of doing it.

Two things it does that Dune cannot:
  1. Uses the launcher wallet we recover locally (creator_fee_recipient role),
     so there is no external dependency or data lag.
  2. Scores devs by ORGANIC migrations — coins that graduated on real buying,
     not bundle/self-funded manipulation. Dune has no verdict signal; it counts
     every graduation equally, so bundlers pollute its list.

Ranking uses the Wilson lower bound of the organic-migration rate so a noisy
2-for-2 dev does not outrank a proven 12-of-40 dev, plus a recency decay so
dormant devs fall off.

Usage:
  # Update the ledger from a finished batch's coins (called by pipeline.py):
  from dev_ledger import update_ledger
  update_ledger(batch_id, coins)          # coins = analyze_batch result_data["all_coins"]

  # Re-rank / rebuild the published watchlist from the current ledger:
  python3 scripts/dev_ledger.py --rank

  # One-time seed from the latest on-disk batch (proves it end to end):
  python3 scripts/dev_ledger.py --seed-latest
"""
import json
import math
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO        = Path(__file__).parent.parent.resolve()
LEDGER_PATH = REPO / "analysis" / "dev-ledger.json"
OUT_PATH    = REPO / "analysis" / "dev-watchlist-live.json"

# ── Tunables ────────────────────────────────────────────────────────────────
RECENCY_HALFLIFE_DAYS = 10.0   # a dev's score halves every 10 idle days
TIER_A_MIN_WILSON     = 0.15   # confidence-adjusted organic rate for Tier A
TIER_A_MIN_ORGANIC    = 2      # need >=2 organic migrations
TIER_B_MIN_WILSON     = 0.05   # lower bar, but needs volume
TIER_B_MIN_MIGRATIONS = 3
MAX_INACTIVE_DAYS      = 21     # drop devs idle longer than this from the list


def now_utc():
    return datetime.now(timezone.utc)


def wilson_lower_bound(successes, n, z=1.96):
    """95% Wilson score lower bound for a binomial rate. Rewards evidence,
    penalizes small samples — 2/2 -> 0.34, 12/40 -> 0.19, 40/50 -> 0.68."""
    if n == 0:
        return 0.0
    p = successes / n
    denom = 1 + z * z / n
    center = p + z * z / (2 * n)
    margin = z * math.sqrt((p * (1 - p) + z * z / (4 * n)) / n)
    return max(0.0, (center - margin) / denom)


def load_ledger():
    if LEDGER_PATH.exists():
        with open(LEDGER_PATH) as f:
            return json.load(f)
    return {"devs": {}, "processed_batches": [], "updated_at": None}


def save_ledger(ledger):
    LEDGER_PATH.parent.mkdir(parents=True, exist_ok=True)
    ledger["updated_at"] = now_utc().isoformat()
    with open(LEDGER_PATH, "w") as f:
        json.dump(ledger, f, indent=2)


def _verdict(coin):
    """Prefer a precomputed verdict; else fall back to pipeline.classify."""
    v = coin.get("verdict")
    if v:
        return v
    try:
        from pipeline import classify
        return classify(coin)
    except Exception:
        return "bundle"


def update_ledger(batch_id, coins, batch_time=None):
    """Fold one batch's coins into the persistent dev ledger. Idempotent:
    a batch already recorded is skipped so re-runs don't double-count."""
    ledger = load_ledger()
    if batch_id in ledger["processed_batches"]:
        return ledger
    ts = (batch_time or now_utc()).isoformat()

    for c in coins:
        dev = c.get("creator")
        if not dev:
            continue
        d = ledger["devs"].get(dev)
        if d is None:
            d = {"launches": 0, "migrations": 0, "organic_migrations": 0,
                 "first_seen": ts, "last_seen": ts, "last_migration": None}
            ledger["devs"][dev] = d
        d["launches"] += 1
        d["last_seen"] = ts
        if c.get("migrated"):
            d["migrations"] += 1
            d["last_migration"] = ts
            if _verdict(c) == "organic":
                d["organic_migrations"] += 1

    ledger["processed_batches"].append(batch_id)
    save_ledger(ledger)
    return ledger


def _recency_factor(last_seen_iso):
    try:
        last = datetime.fromisoformat(last_seen_iso)
    except Exception:
        return 0.0
    days = max(0.0, (now_utc() - last).total_seconds() / 86400.0)
    return 0.5 ** (days / RECENCY_HALFLIFE_DAYS)


def rank(ledger=None, write=True):
    """Score every dev and emit a ranked, tiered watchlist. The score blends the
    confidence-adjusted organic rate with recency so hot devs float to the top."""
    ledger = ledger or load_ledger()
    rows = []
    for dev, d in ledger["devs"].items():
        L = d["launches"]; M = d["migrations"]; O = d["organic_migrations"]
        if L == 0:
            continue
        recency = _recency_factor(d["last_seen"])
        days_inactive = round((now_utc() - datetime.fromisoformat(d["last_seen"])).total_seconds() / 86400.0, 1)
        if days_inactive > MAX_INACTIVE_DAYS:
            continue
        wilson_organic = wilson_lower_bound(O, L)
        wilson_migrate = wilson_lower_bound(M, L)
        score = round(wilson_organic * recency * math.log1p(O) * 100, 3)

        # Every published dev needs real (organic) evidence — a high migration
        # rate built purely on bundling is not a winner we'd want to buy.
        if O < 1:
            continue
        if wilson_organic >= TIER_A_MIN_WILSON and O >= TIER_A_MIN_ORGANIC:
            tier = "A"
        elif wilson_migrate >= TIER_B_MIN_WILSON and M >= TIER_B_MIN_MIGRATIONS:
            tier = "B"
        else:
            continue  # not reliable enough to publish

        rows.append({
            "wallet": dev,
            "tier": tier,
            "launches": L,
            "migrations": M,
            "organic_migrations": O,
            "organic_rate_pct": round(100 * O / L, 1),
            "migration_rate_pct": round(100 * M / L, 1),
            "wilson_organic": round(wilson_organic, 3),
            "days_inactive": days_inactive,
            "score": score,
            "last_seen": d["last_seen"],
        })

    rows.sort(key=lambda r: r["score"], reverse=True)
    out = {
        "generated_at": now_utc().isoformat(),
        "source": "local-pipeline-ledger",
        "total_devs_tracked": len(ledger["devs"]),
        "batches_processed": len(ledger["processed_batches"]),
        "watchlist_count": len(rows),
        "tier_a": sum(1 for r in rows if r["tier"] == "A"),
        "tier_b": sum(1 for r in rows if r["tier"] == "B"),
        "wallets": rows,
    }
    if write:
        with open(OUT_PATH, "w") as f:
            json.dump(out, f, indent=2)
    return out


def seed_latest():
    """Process the most recent on-disk batch through analyze_batch and fold it
    into the ledger — a one-shot proof the whole path works right now."""
    sys.path.insert(0, str(REPO / "scripts"))
    import pipeline
    base = pipeline.DATA_ROOT_BASE / "batches"
    def batch_num(p):
        try:    return int(p.name.split("-")[1])
        except: return -1
    batches = sorted([p for p in base.iterdir() if p.name.startswith("batch-")],
                     key=batch_num, reverse=True)
    latest, run_id = None, None
    for b in batches:
        runs_dir = b / "runs"
        if not runs_dir.exists():
            continue
        runs = sorted(runs_dir.iterdir())
        if runs:
            latest, run_id = b, runs[-1].name
            break
    if latest is None:
        sys.exit("no on-disk batch with raw run data found")
    print(f"Seeding from {latest.name} / {run_id} ...")
    result = pipeline.analyze_batch(latest.name, latest, run_id,
                                    dev_watchlist=pipeline.load_dev_watchlist())
    coins = result["all_coins"]
    for c in coins:
        c["verdict"] = pipeline.classify(c)
    have_dev = sum(1 for c in coins if c.get("creator"))
    print(f"  {len(coins)} coins, {have_dev} with dev wallet "
          f"({100*have_dev/len(coins):.0f}% coverage)")
    update_ledger(latest.name, coins)
    out = rank()
    print(f"  ledger: {out['total_devs_tracked']} devs tracked, "
          f"{out['watchlist_count']} pass the bar "
          f"(A={out['tier_a']}, B={out['tier_b']})")
    return out


if __name__ == "__main__":
    if "--seed-latest" in sys.argv:
        seed_latest()
    elif "--rank" in sys.argv:
        out = rank()
        print(f"Ranked {out['watchlist_count']} devs "
              f"(A={out['tier_a']}, B={out['tier_b']}) from "
              f"{out['batches_processed']} batches")
    else:
        print(__doc__)
