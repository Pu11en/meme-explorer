#!/usr/bin/env python3
"""
Real-time dev-reputation ledger — find wallets that launch winners, fast.

Unlike the Dune watchlist (a 3-min batch SQL query regenerated by hand every
couple weeks), this accumulates from our OWN recordings, one batch at a time,
while the raw wallet data is still on disk. A dev who lands their 2nd organic
migration surfaces in the ranked list within ~1 hour of doing it.

Two things it does that Dune cannot:
  1. Uses the launcher wallet we recover locally (creator_fee_recipient role),
     so there is no external dependency or data lag.
  2. Scores devs by ORGANIC migrations — coins that graduated on real buying,
     not bundle/self-funded manipulation. Dune has no verdict signal; it counts
     every graduation equally, so bundlers pollute its list.

Ranking uses the Wilson lower bound of the organic-migration rate so a noisy
2-for-2 dev does not outrank a proven 12-of-40 dev, plus a recency decay so
dormant devs fall off.

Usage:
  # Update the ledger from a finished batch's coins (called by pipeline.py):
  from dev_ledger import update_ledger
  update_ledger(batch_id, coins)          # coins = analyze_batch result_data["all_coins"]

  # Re-rank / rebuild the published watchlist from the current ledger:
  python3 scripts/dev_ledger.py --rank

  # One-time seed from the latest on-disk batch (proves it end to end):
  python3 scripts/dev_ledger.py --seed-latest
"""
import fcntl
import json
import os
import sys
import math
from datetime import datetime, timezone
from pathlib import Path

REPO        = Path(__file__).parent.parent.resolve()
LEDGER_PATH = REPO / "analysis" / "dev-ledger.json"
OUT_PATH    = REPO / "analysis" / "dev-watchlist-live.json"
LOCK_PATH   = REPO / "analysis" / ".dev-ledger.lock"

# ── Tunables ────────────────────────────────────────────────────────────────
RECENCY_HALFLIFE_DAYS = 10.0   # a dev's score halves every 10 idle days
TIER_A_MIN_WILSON     = 0.15   # confidence-adjusted organic rate for Tier A
TIER_A_MIN_ORGANIC    = 2      # need >=2 organic migrations
TIER_B_MIN_WILSON     = 0.05   # lower bar, but needs volume
TIER_B_MIN_MIGRATIONS = 3
MAX_INACTIVE_DAYS      = 21     # drop devs idle longer than this from the list

# Long-running hygiene: without pruning the ledger grows unbounded (~1.4k new
# devs/hour, most launch once and never migrate). Drop devs that are stale AND
# never produced a migration — they can never qualify, so we lose nothing.
PRUNE_INACTIVE_DAYS    = 30     # never-migrated devs idle this long are dropped
PRUNE_MIGRATED_DAYS    = 120    # even a once-migrated dev is dropped after this long idle (bounds growth)
MAX_PROCESSED_BATCHES  = 5000   # keep the dedupe list bounded (~7 months hourly)
PROFIT_HIT_PCT         = 50.0   # a coin counts as "would've been profitable" at >=+50% best-case in-window


def now_utc():
    return datetime.now(timezone.utc)


def wilson_lower_bound(successes, n, z=1.96):
    """95% Wilson score lower bound for a binomial rate. Rewards evidence,
    penalizes small samples — 2/2 -> 0.34, 12/40 -> 0.19, 40/50 -> 0.68."""
    if n == 0:
        return 0.0
    p = successes / n
    denom = 1 + z * z / n
    center = p + z * z / (2 * n)
    margin = z * math.sqrt((p * (1 - p) + z * z / (4 * n)) / n)
    return max(0.0, (center - margin) / denom)


def _empty_ledger():
    return {"devs": {}, "processed_batches": [], "updated_at": None}


def load_ledger():
    if not LEDGER_PATH.exists():
        return _empty_ledger()
    try:
        with open(LEDGER_PATH) as f:
            data = json.load(f)
        # sanity: expected shape
        if not isinstance(data.get("devs"), dict) or not isinstance(data.get("processed_batches"), list):
            raise ValueError("ledger missing expected keys")
        return data
    except Exception as e:
        # Corruption (e.g. truncated by a crash mid-write). Quarantine the bad
        # file so a human can inspect it, then start fresh rather than bricking
        # every future batch. The atomic writer below makes this rare.
        bad = LEDGER_PATH.with_suffix(f".corrupt-{now_utc().strftime('%Y%m%dT%H%M%S')}")
        try:
            LEDGER_PATH.replace(bad)
            sys.stderr.write(f"[dev_ledger] corrupt ledger ({e}); quarantined to {bad.name}, starting fresh\n")
        except Exception:
            pass
        return _empty_ledger()


def save_ledger(ledger):
    """Atomic write: dump to a temp file in the same dir, fsync, then os.replace
    (atomic rename). A crash can never leave a half-written ledger."""
    LEDGER_PATH.parent.mkdir(parents=True, exist_ok=True)
    ledger["updated_at"] = now_utc().isoformat()
    tmp = LEDGER_PATH.with_suffix(".tmp")
    try:
        with open(tmp, "w") as f:
            json.dump(ledger, f, indent=2)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, LEDGER_PATH)
    except Exception:
        # e.g. disk full mid-write — don't leave a partial temp lying around,
        # and re-raise so the caller/health check sees the failure.
        try:
            tmp.unlink(missing_ok=True)
        except Exception:
            pass
        raise


class _FileLock:
    """Cross-process advisory lock so concurrent post_process threads (and a
    manual seed run) can't clobber each other's ledger updates."""
    def __init__(self, path):
        self.path = path
        self.fd = None
    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.fd = open(self.path, "w")
        fcntl.flock(self.fd, fcntl.LOCK_EX)
        return self
    def __exit__(self, *a):
        try:
            fcntl.flock(self.fd, fcntl.LOCK_UN)
        finally:
            self.fd.close()


def _verdict(coin):
    """Prefer a precomputed verdict; else fall back to pipeline.classify."""
    v = coin.get("verdict")
    if v:
        return v
    try:
        from pipeline import classify
        return classify(coin)
    except Exception:
        return "bundle"


def _prune(ledger):
    """Drop dead weight so the file stays bounded over months. Never-migrated
    devs go after PRUNE_INACTIVE_DAYS idle; even migrated devs go after the
    longer PRUNE_MIGRATED_DAYS (they're long past qualifying by then), so the
    'devs' map cannot grow without bound. Also caps the dedupe list."""
    now = now_utc()
    keep = {}
    for dev, d in ledger["devs"].items():
        try:
            idle_days = (now - datetime.fromisoformat(d["last_seen"])).total_seconds() / 86400.0
        except Exception:
            idle_days = 0
        cutoff = PRUNE_MIGRATED_DAYS if d.get("migrations", 0) > 0 else PRUNE_INACTIVE_DAYS
        if idle_days > cutoff:
            continue
        keep[dev] = d
    ledger["devs"] = keep
    pb = ledger["processed_batches"]
    if len(pb) > MAX_PROCESSED_BATCHES:
        ledger["processed_batches"] = pb[-MAX_PROCESSED_BATCHES:]


def update_ledger(batch_id, coins, batch_time=None):
    """Fold one batch's coins into the persistent dev ledger. Idempotent:
    a batch already recorded is skipped so re-runs don't double-count. Guarded
    by a cross-process lock and written atomically."""
    with _FileLock(LOCK_PATH):
        ledger = load_ledger()
        if batch_id in ledger["processed_batches"]:
            return ledger
        ts = (batch_time or now_utc()).isoformat()

        for c in coins:
            dev = c.get("creator")
            if not dev:
                continue
            d = ledger["devs"].get(dev)
            if d is None:
                d = {"launches": 0, "migrations": 0, "organic_migrations": 0,
                     "first_seen": ts, "last_seen": ts, "last_migration": None,
                     "gain_samples": 0, "gain_sum_pct": 0.0, "profit_hits": 0,
                     "hold_sum_pct": 0.0, "hold_wins": 0}
                ledger["devs"][dev] = d
            for k, v in (("gain_samples", 0), ("gain_sum_pct", 0.0), ("profit_hits", 0),
                         ("hold_sum_pct", 0.0), ("hold_wins", 0)):
                d.setdefault(k, v)               # backfill fields for pre-existing devs
            d["launches"] += 1
            d["last_seen"] = ts
            if c.get("migrated"):
                d["migrations"] += 1
                d["last_migration"] = ts
                if _verdict(c) == "organic":
                    d["organic_migrations"] += 1
            # "Would you have made money?" — accumulate two returns per tradable
            # coin: best-case (perfect exit at peak, a ceiling) and realistic
            # (bought ~30s in, held, sold at window end — CAN be negative).
            g = c.get("max_gain_pct")
            if g is not None:
                d["gain_samples"] += 1
                d["gain_sum_pct"] += g
                if g >= PROFIT_HIT_PCT:
                    d["profit_hits"] += 1
            h = c.get("hold_gain_pct")
            if h is not None:
                d["hold_sum_pct"] += h
                if h > 0:
                    d["hold_wins"] += 1

        ledger["processed_batches"].append(batch_id)
        _prune(ledger)
        save_ledger(ledger)
        return ledger


def _recency_factor(last_seen_iso):
    try:
        last = datetime.fromisoformat(last_seen_iso)
    except Exception:
        return 0.0
    days = max(0.0, (now_utc() - last).total_seconds() / 86400.0)
    return 0.5 ** (days / RECENCY_HALFLIFE_DAYS)


def rank(ledger=None, write=True):
    """Score every dev and emit a ranked, tiered watchlist. The score blends the
    confidence-adjusted organic rate with recency so hot devs float to the top."""
    ledger = ledger or load_ledger()
    rows = []
    for dev, d in ledger["devs"].items():
        L = d["launches"]; M = d["migrations"]; O = d["organic_migrations"]
        if L == 0:
            continue
        recency = _recency_factor(d["last_seen"])
        days_inactive = round((now_utc() - datetime.fromisoformat(d["last_seen"])).total_seconds() / 86400.0, 1)
        if days_inactive > MAX_INACTIVE_DAYS:
            continue
        wilson_organic = wilson_lower_bound(O, L)
        wilson_migrate = wilson_lower_bound(M, L)
        score = round(wilson_organic * recency * math.log1p(O) * 100, 3)

        # Every published dev needs real (organic) evidence — a high migration
        # rate built purely on bundling is not a winner we'd want to buy.
        if O < 1:
            continue
        if wilson_organic >= TIER_A_MIN_WILSON and O >= TIER_A_MIN_ORGANIC:
            tier = "A"
        elif wilson_migrate >= TIER_B_MIN_WILSON and M >= TIER_B_MIN_MIGRATIONS:
            tier = "B"
        else:
            continue  # not reliable enough to publish

        # Money proxy (CEILING, not expected profit): across this dev's coins we
        # could have entered by hand, the best-case return of buying ~30s in and
        # selling at the later peak. Real returns are lower (no perfect exit, plus
        # slippage/fees/MEV). Only coins with a tradable post-entry buy count.
        gs = d.get("gain_samples", 0)
        avg_gain_pct  = round(d.get("gain_sum_pct", 0.0) / gs, 1) if gs else None
        profit_rate   = round(100 * d.get("profit_hits", 0) / gs, 1) if gs else None
        # The realistic pair: held to window end, so it can be (and often is) negative.
        realistic_gain = round(d.get("hold_sum_pct", 0.0) / gs, 1) if gs else None
        realistic_win  = round(100 * d.get("hold_wins", 0) / gs, 1) if gs else None

        rows.append({
            "wallet": dev,
            "tier": tier,
            "launches": L,
            "migrations": M,
            "organic_migrations": O,
            "organic_rate_pct": round(100 * O / L, 1),
            "migration_rate_pct": round(100 * M / L, 1),
            "wilson_organic": round(wilson_organic, 3),
            # Money proxies, bracketing reality. Trust the realistic pair; the
            # best-case pair is an unreachable ceiling (perfect exit, no costs).
            "realistic_avg_gain_pct": realistic_gain,   # bought ~30s in, sold at window end — CAN be negative
            "realistic_win_rate_pct": realistic_win,    # % of tradable coins where that hold was profitable
            "best_case_avg_gain_pct": avg_gain_pct,     # CEILING only — perfect peak exit, never negative
            "best_case_profit_rate_pct": profit_rate,
            "gain_samples": gs,                         # how many of their coins these are based on
            "days_inactive": days_inactive,
            "score": score,
            "last_seen": d["last_seen"],
        })

    rows.sort(key=lambda r: r["score"], reverse=True)
    out = {
        "generated_at": now_utc().isoformat(),
        "source": "local-pipeline-ledger",
        "total_devs_tracked": len(ledger["devs"]),
        "batches_processed": len(ledger["processed_batches"]),
        "watchlist_count": len(rows),
        "tier_a": sum(1 for r in rows if r["tier"] == "A"),
        "tier_b": sum(1 for r in rows if r["tier"] == "B"),
        "wallets": rows,
    }
    if write:
        with open(OUT_PATH, "w") as f:
            json.dump(out, f, indent=2)
    return out


def seed_latest():
    """Process the most recent on-disk batch through analyze_batch and fold it
    into the ledger — a one-shot proof the whole path works right now."""
    sys.path.insert(0, str(REPO / "scripts"))
    import pipeline
    base = pipeline.DATA_ROOT_BASE / "batches"
    def batch_num(p):
        try:    return int(p.name.split("-")[1])
        except: return -1
    batches = sorted([p for p in base.iterdir() if p.name.startswith("batch-")],
                     key=batch_num, reverse=True)
    latest, run_id = None, None
    for b in batches:
        runs_dir = b / "runs"
        if not runs_dir.exists():
            continue
        runs = sorted(runs_dir.iterdir())
        if runs:
            latest, run_id = b, runs[-1].name
            break
    if latest is None:
        sys.exit("no on-disk batch with raw run data found")
    print(f"Seeding from {latest.name} / {run_id} ...")
    result = pipeline.analyze_batch(latest.name, latest, run_id,
                                    dev_watchlist=pipeline.load_dev_watchlist())
    coins = result["all_coins"]
    for c in coins:
        c["verdict"] = pipeline.classify(c)
    have_dev = sum(1 for c in coins if c.get("creator"))
    print(f"  {len(coins)} coins, {have_dev} with dev wallet "
          f"({100*have_dev/len(coins):.0f}% coverage)")
    update_ledger(latest.name, coins)
    out = rank()
    print(f"  ledger: {out['total_devs_tracked']} devs tracked, "
          f"{out['watchlist_count']} pass the bar "
          f"(A={out['tier_a']}, B={out['tier_b']})")
    return out


if __name__ == "__main__":
    if "--seed-latest" in sys.argv:
        seed_latest()
    elif "--rank" in sys.argv:
        out = rank()
        print(f"Ranked {out['watchlist_count']} devs "
              f"(A={out['tier_a']}, B={out['tier_b']}) from "
              f"{out['batches_processed']} batches")
    else:
        print(__doc__)
